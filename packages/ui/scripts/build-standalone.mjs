/**
 * build-standalone.mjs — produces a single-file JS bundle entry and a single
 * concatenated CSS file that ship in `cdn/` for the AI-skill mockup use case:
 *
 *   cdn/standalone.js   — registers every mockup-eligible element (one <script>
 *                         loads all 22 tags). Built by Vite using the entry
 *                         this script writes to src/_generated/.
 *   cdn/standalone.css  — preset (tokens + base) + every per-element CSS,
 *                         concatenated. One <link> instead of N.
 *
 * Runs after `vp build --config vite.config.css.ts` (CSS dist must exist) and
 * before `vp build` (Vite picks up the generated entry).
 */
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// eslint-disable-next-line no-underscore-dangle -- ESM idiom
const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(__dirname, '..');
const MANIFEST_PATH = resolve(PKG_ROOT, 'elements.json');
const ENTRY_OUT = resolve(PKG_ROOT, 'src/_generated/cdn-standalone-entry.ts');
const CSS_OUT = resolve(PKG_ROOT, 'cdn/standalone.css');
const CSS_DIST_DIR = resolve(PKG_ROOT, 'dist/css');

const manifest = JSON.parse(await readFile(MANIFEST_PATH, 'utf-8'));

// Elements eligible for the standalone bundle: everything that can appear in
// a mockup (custom elements with `inMockups: true`). Each element — including
// sub-items like `dropdown-item` — has its own index.ts with a `define()` call.
const customElements = manifest.elements.filter((e) => e.inMockups && e.kind !== 'native');

// ──────────────────────────── JS entry ────────────────────────────────────────

async function writeEntry() {
  await mkdir(dirname(ENTRY_OUT), { recursive: true });
  const lines = [
    '// AUTO-GENERATED by scripts/build-standalone.mjs — do not edit.',
    '// Side-effect imports register every mockup-eligible element with the',
    '// custom-elements registry. The Vite plugin (or the CLI substitution',
    '// applied at consumer-run time) rewrites the prefix at build time.',
    '',
  ];
  for (const e of customElements) {
    lines.push(`import './../html/elements/${e.name}/index';`);
  }
  // Also re-export setPrefix for advanced runtime use (tests, dynamic switch).
  lines.push('');
  lines.push("export { setPrefix, getPrefix } from '../html/registry';");
  lines.push('');
  await writeFile(ENTRY_OUT, lines.join('\n'), 'utf-8');
  console.log(`[standalone] wrote ${ENTRY_OUT}`);
}

// ──────────────────────────── CSS bundle ──────────────────────────────────────

// Concatenates preset.css + every per-element CSS file from dist/css/ into one
// standalone.css. Skips appearance-variant subdirectories (CSS already merges
// them into siblings via @import — the consumer picks the visual variant when
// they author the mockup, here we just expose them all under the same file).
async function buildCss() {
  const parts = [
    '/* Luxen UI standalone bundle — concatenated by scripts/build-standalone.mjs */',
    '',
    `/* preset.css (tokens + base) */`,
    (await readFile(join(CSS_DIST_DIR, 'preset.css'), 'utf-8')).trim(),
    '',
  ];

  const elementsDir = join(CSS_DIST_DIR, 'elements');
  const files = await listCssFiles(elementsDir);
  for (const file of files) {
    parts.push(`/* ${file.relPath} */`);
    parts.push((await readFile(file.absPath, 'utf-8')).trim());
    parts.push('');
  }

  await writeFile(CSS_OUT, parts.join('\n'), 'utf-8');
  console.log(`[standalone] wrote ${CSS_OUT} (${files.length} element CSS files concatenated)`);
}

// Walk dist/css/elements/ and return every .css file, including those nested
// in appearance subdirectories. Sorted for determinism.
async function listCssFiles(dir) {
  const out = [];
  async function walk(current, rel) {
    /* eslint-disable no-await-in-loop -- sequential walk is fine for ~20 files */
    const entries = await readdir(current, { withFileTypes: true });
    for (const entry of entries.toSorted((a, b) => a.name.localeCompare(b.name))) {
      const absPath = join(current, entry.name);
      const relPath = rel ? `${rel}/${entry.name}` : entry.name;
      if (entry.isDirectory()) await walk(absPath, relPath);
      else if (entry.isFile() && entry.name.endsWith('.css')) out.push({ absPath, relPath });
    }
    /* eslint-enable no-await-in-loop */
  }
  await walk(dir, '');
  return out;
}

// ──────────────────────────── Main ────────────────────────────────────────────

await writeEntry();
await buildCss();
